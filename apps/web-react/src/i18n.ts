export const fmt = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)(?::([^}]+))?\}/g, (_, k, format) => {
    const value = vars[k] ?? "";
    if (format === "02d" && typeof value === "number") return value.toString().padStart(2, "0");
    return String(value);
  });
